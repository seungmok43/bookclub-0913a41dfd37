#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build community/catalog.js from the book folders that are committed in git.

Why: the library and the resource list must follow the real folders, not a
hand-kept list. Only git-tracked session pages are listed, so unfinished
work in the working tree never shows up as a link.

Title/author come from the session JSON files that the existing pages were
built from (book, author fields only -- nothing else is copied).
Dates come from the folder names. Unknown values stay empty.

Usage:
  python3 tools/build_catalog.py [path/to/sessions_rich]
"""
import datetime, glob, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_META = os.path.join(ROOT, '..', '..', '북클럽-웹', 'sessions_rich')
META_DIR = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_META
SKIP = {'community', 'assets', 'covers', 'docs', 'supabase', 'tools', '_pv'}
DAYS = '월화수목금토일'

tracked = subprocess.run(['git', 'ls-files'], cwd=ROOT, capture_output=True,
                         text=True, check=True).stdout.splitlines()
books = {}
for path in tracked:
    m = re.fullmatch(r'([a-z0-9-]+)/index\.html', path)
    if m and m.group(1) not in SKIP:
        books.setdefault(m.group(1), [])
for path in tracked:
    m = re.fullmatch(r'([a-z0-9-]+)/(\d{4}-\d{2}-\d{2})/index\.html', path)
    if m and m.group(1) in books:
        books[m.group(1)].append(m.group(2))


def meta_for(slug):
    title = author = ''
    dates = []
    for f in sorted(glob.glob(os.path.join(META_DIR, slug, '*.json'))):
        try:
            d = json.load(open(f, encoding='utf-8'))
        except Exception:
            continue
        title = title or (d.get('book') or '')
        author = author or (d.get('author') or '')
        if re.fullmatch(r'\d{4}-\d{2}-\d{2}', d.get('date') or ''):
            dates.append(d['date'])
    return title, author, dates


def cover_for(slug):
    for ext in ('jpg', 'svg', 'png'):
        if f'covers/{slug}.{ext}' in tracked:
            return f'covers/{slug}.{ext}'
    return ''


out = []
for slug in sorted(books):
    title, author, meta_dates = meta_for(slug)
    dates = sorted(books[slug])
    # A book whose whole record is its book page (no dated sub-folders):
    # take the date from its source JSON and link the book page itself.
    own_page = not dates
    if own_page:
        dates = sorted(set(meta_dates))
    out.append({
        'slug': slug,
        'title': title,
        'author': author,
        'cover': cover_for(slug),
        'sessions': [{
            'date': d,
            'day': DAYS[datetime.date.fromisoformat(d).weekday()],
            'round': i + 1,
            'href': f'{slug}/' if own_page else f'{slug}/{d}/',
        } for i, d in enumerate(dates)],
    })
# newest-read first
out.sort(key=lambda b: (b['sessions'][-1]['date'] if b['sessions'] else ''), reverse=True)

js = ('// Generated by tools/build_catalog.py -- do not edit by hand.\n'
      '// Re-run after adding a book folder or a session folder.\n'
      'window.BOOKLOVE_CATALOG = [\n' +
      ',\n'.join(json.dumps(b, ensure_ascii=False) for b in out) + '\n];\n')
open(os.path.join(ROOT, 'community', 'catalog.js'), 'w', encoding='utf-8').write(js)
print(f'{len(out)} books, {sum(len(b["sessions"]) for b in out)} sessions')
for b in out:
    print(f"  {b['slug']:20} {len(b['sessions']):2}  {b['title'] or '(no title)'} / {b['author'] or '-'}")
