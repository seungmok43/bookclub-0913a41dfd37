#!/usr/bin/env python3
"""Build v2/data.js from the live repo (re-runnable, read-only on everything outside v2/).

Sources (existing text only — no new prose):
  community/catalog.js      books, sessions (date, day, round, href)
  v1/index.html  const BOOKS  (old hub, moved from the root)   hub one-liner `s`, days `d`, period `p`, tone, cover override
  <book>/index.html         cover image actually shown on the book page
  <session>/index.html      hook = p.oneliner or div.lead (tags stripped), subheads = h2/h3 text

Locked sessions would be listed with locked=true and no hook. Since 2026-11-22 there are none:
the three mom pages (07-31 / 08-14 / 08-21) are open pages; the old key-locked files are kept as
mom/<date>/index_locked_archive.html and are not read here.
Usage:  python3 v2/build_data.py      (run from anywhere)
"""
import html, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCKED = set()


def read(p):
    with open(os.path.join(ROOT, p), encoding='utf-8') as f:
        return f.read()


def text(frag):
    frag = re.sub(r'<span class="qm">.*?</span>', '', frag, flags=re.S)
    frag = re.sub(r'<[^>]+>', '', frag)
    return re.sub(r'\s+', ' ', html.unescape(frag)).strip()


def catalog():
    rows = [json.loads(l.rstrip().rstrip(',')) for l in read('community/catalog.js').splitlines() if l.startswith('{')]
    if not rows:
        sys.exit('catalog.js: no rows')
    return rows


def hub_books():
    m = re.search(r'const BOOKS=(\[.*?\]);\n', read('v1/index.html'), re.S)
    if not m:
        sys.exit('v1/index.html: const BOOKS not found')
    return {b['slug'].strip('/'): b for b in json.loads(m.group(1))}


def book_cover(slug):
    p = os.path.join(slug, 'index.html')
    if not os.path.exists(os.path.join(ROOT, p)):
        return ''
    m = re.search(r'<img[^>]*src="\.\./(covers/[^"]+)"', read(p))
    return m.group(1) if m else ''


def session_info(href):
    p = href + 'index.html'
    if not os.path.exists(os.path.join(ROOT, p)):
        return '', []
    t = read(p)
    t = re.sub(r'(src|href)="data:[^"]*"', r'\1=""', t)  # drop inline images before scanning
    m = re.search(r'<p class="oneliner"[^>]*>(.*?)</p>', t, re.S) or re.search(r'<div class="lead"[^>]*>(.*?)</div>', t, re.S)
    heads = [{'l': int(l), 't': text(x)} for l, x in re.findall(r'<h([23])[^>]*>(.*?)</h\1>', t, re.S)]
    return (text(m.group(1)) if m else ''), [h for h in heads if h['t']]


def main():
    hub = hub_books()
    books = []
    for r in catalog():
        slug = r['slug']
        hb = hub.get(slug, {})
        cover = book_cover(slug) or (r.get('cover') if r.get('cover') and os.path.exists(os.path.join(ROOT, r['cover'])) else '')
        sessions = []
        for s in r['sessions']:
            locked = s['href'] in LOCKED
            hook, heads = ('', []) if locked else session_info(s['href'])
            if not hook and not locked and s['href'] == slug + '/':
                hook = hb.get('s', '')          # single-page book (pai): the page is the session
            sessions.append({'date': s['date'], 'day': s['day'], 'round': s['round'], 'href': s['href'],
                             'hook': hook, 'heads': heads, 'locked': locked})
        books.append({'slug': slug, 'title': r.get('title') or hb.get('t', ''), 'author': r.get('author') or hb.get('a', ''),
                      'cover': cover, 'tone': hb.get('tone', ''), 'days': hb.get('d', []), 'period': hb.get('p', ''),
                      'hook': hb.get('s', ''), 'href': slug + '/', 'sessions': sessions})
    missing = [b['slug'] + ':' + s['date'] for b in books for s in b['sessions'] if not s['hook'] and not s['locked']]
    out = ('// Generated by v2/build_data.py -- do not edit by hand.\n'
           'window.V2_DATA = ' + json.dumps({'books': books}, ensure_ascii=False, indent=0) + ';\n')
    with open(os.path.join(ROOT, 'v2', 'data.js'), 'w', encoding='utf-8') as f:
        f.write(out)
    ns = sum(len(b['sessions']) for b in books)
    print(f'books={len(books)} sessions={ns} locked={sum(s["locked"] for b in books for s in b["sessions"])} '
          f'no_hook={missing} no_cover={[b["slug"] for b in books if not b["cover"]]}')


if __name__ == '__main__':
    main()
