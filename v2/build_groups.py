#!/usr/bin/env python3
"""Build v2/groups.js from the curation draft table (re-runnable).
Source: 4_콘텐츠출판국/_보고/북클럽_질문별묶음_초안_20261120.md (path may be given as argv[1]).
groups = the 6 rows of 「묶음 여섯 개」 in table order (q without the circled number, line = editor line),
slugs  = books whose PRIMARY group (first circled number in the 묶음 column) is that group, in 책별 표 order.
forWhom = the 「이런 분께」 column. draft stays true until the owner approves."""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    '~/Desktop/javis/4_콘텐츠출판국/_보고/북클럽_질문별묶음_초안_20261120.md')
CIRC = '①②③④⑤⑥⑦⑧⑨'
t = open(SRC, encoding='utf-8').read()
rows = [[c.strip() for c in l.strip().strip('|').split('|')] for l in t.splitlines() if l.startswith('|') and not l.startswith('|---')]
groups, books = [], []
for r in rows:
    if len(r) == 3 and r[0][:1] in CIRC:
        groups.append({'n': CIRC.index(r[0][0]), 'q': r[0][1:].strip(), 'line': r[1], 'slugs': []})
    elif len(r) == 6 and r[3][:1] in CIRC:
        books.append((r[0], CIRC.index(r[3][0]), r[4]))
by = {g['n']: g for g in groups}
for slug, n, _ in books:
    by[n]['slugs'].append(slug)
known = {json.loads(l.rstrip().rstrip(','))['slug'] for l in open(os.path.join(ROOT, 'community/catalog.js'), encoding='utf-8') if l.startswith('{')}
slugs = [b[0] for b in books]
assert len(groups) == 6, len(groups)
assert sorted(slugs) == sorted(known) and len(set(slugs)) == len(slugs), (set(known) ^ set(slugs))
out = {'draft': True, 'groups': [{k: g[k] for k in ('q', 'line', 'slugs')} for g in groups],
       'forWhom': {s: w for s, _, w in books}}
with open(os.path.join(ROOT, 'v2', 'groups.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by v2/build_groups.py from the curation DRAFT table — the owner edits and decides.\n'
            '// draft:true shows the grey 「초안」 tag on group lines and 「이런 분께」 lines.\n'
            'window.V2_GROUPS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
print('groups', [(g['q'], len(g['slugs'])) for g in out['groups']], 'forWhom', len(out['forWhom']))
